def inject_after_once(text: str, anchor: str, insertion: str, label: str) -> str:
    count = text.count(anchor)
    if count != 1:
        raise RuntimeError(f"{label}: expected one anchor, found {count}: {anchor!r}")
    return text.replace(anchor, anchor + insertion, 1)


def inject_before_once(text: str, anchor: str, insertion: str, label: str) -> str:
    count = text.count(anchor)
    if count != 1:
        raise RuntimeError(f"{label}: expected one anchor, found {count}: {anchor!r}")
    return text.replace(anchor, insertion + anchor, 1)


