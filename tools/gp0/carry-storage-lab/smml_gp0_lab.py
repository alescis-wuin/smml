def verify_clean_root(root: Path) -> None:
    if not (root / "Survival").is_dir() or not (root / "Data").is_dir():
        raise SystemExit(f"Not a Scrap Mechanic root: {root}")
    problems: list[str] = []
    for rel, expected in TARGETS.items():
        p = root / rel
        if not p.is_file():
            problems.append(f"MISSING {rel}")
            continue
        actual = sha256_file(p)
        if actual != expected:
            problems.append(f"MODIFIED {rel}\n  expected {expected}\n  actual   {actual}")
    cache = root / CACHE_PATH
    if not cache.is_file():
        problems.append(f"MISSING {CACHE_PATH}")
    elif sha256_file(cache) != CACHE_SHA256:
        problems.append(f"MODIFIED {CACHE_PATH}\n  expected {CACHE_SHA256}\n  actual   {sha256_file(cache)}")
    for rel in list(RUNTIME_FILES) + [CONFIG_PATH]:
        if (root / rel).exists():
            problems.append(f"EXTRA {rel} already exists")
    if problems:
        raise SystemExit("Preflight failed:\n" + "\n".join(problems))


def snapshot_tree(source: Path, destination: Path) -> dict:
    if destination.exists():
        raise SystemExit(f"Snapshot destination already exists: {destination}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(source, destination, symlinks=True)
    entries = []
    for p in sorted(destination.rglob("*")):
        rel = p.relative_to(destination).as_posix()
        if p.is_symlink():
            entries.append({"path": rel, "kind": "symlink", "target": os.readlink(p)})
        elif p.is_file():
            entries.append({"path": rel, "kind": "file", "size": p.stat().st_size, "sha256": sha256_file(p)})
        elif p.is_dir():
            entries.append({"path": rel, "kind": "dir"})
    manifest = {
        "schema": "smml-gp0-save-snapshot/1",
        "created_at_utc": utc_now(),
        "source": str(source),
        "entries": entries,
    }
    manifest_bytes = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    atomic_write(destination.parent / "snapshot-manifest.json", manifest_bytes)
    manifest["manifest_sha256"] = sha256_bytes(manifest_bytes)
    return manifest


def verify_snapshot(snapshot_dir: Path, manifest: dict) -> list[str]:
    problems: list[str] = []
    for entry in manifest.get("entries", []):
        p = snapshot_dir / entry["path"]
        kind = entry["kind"]
        if kind == "file":
            if not p.is_file():
                problems.append(f"MISSING {entry['path']}")
            elif p.stat().st_size != entry["size"] or sha256_file(p) != entry["sha256"]:
                problems.append(f"DRIFT {entry['path']}")
        elif kind == "dir":
            if not p.is_dir():
                problems.append(f"MISSING DIR {entry['path']}")
        elif kind == "symlink":
            if not p.is_symlink() or os.readlink(p) != entry["target"]:
                problems.append(f"DRIFT SYMLINK {entry['path']}")
    return problems


def invalidate_current_cache(root: Path, state_dir: Path, state: dict, reason: str) -> None:
    cp = root / CACHE_PATH
    if cp.exists():
        quarantine = state_dir / "quarantine" / f"core_data.cbo.{reason}-{datetime.now().strftime('%Y%m%d-%H%M%S')}"
        quarantine.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(cp), str(quarantine))
        state.setdefault("cache", {}).setdefault("quarantined", []).append(str(quarantine))


def install(args: argparse.Namespace) -> None:
    require_game_stopped()
    root = args.game_root.expanduser().resolve()
    state_dir = args.state_dir.expanduser().resolve()
    if state_path(state_dir).exists():
        old = json.loads(state_path(state_dir).read_text("utf-8"))
        if old.get("installed"):
            raise SystemExit(f"Lab already installed according to {state_path(state_dir)}")
    verify_clean_root(root)

    package_dir = Path(__file__).resolve().parent
    backup_dir = state_dir / "backups"
    backup_dir.mkdir(parents=True, exist_ok=True)

    prepared: dict[str, bytes] = {}
    records: dict[str, dict] = {}
    for rel, expected in TARGETS.items():
        src = root / rel
        original = src.read_bytes()
        if sha256_bytes(original) != expected:
            raise SystemExit(f"Preflight changed during install: {rel}")
        patched = apply_patch(rel, original)
        prepared[rel] = patched
        backup = backup_dir / rel
        backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, backup)
        records[rel] = {
            "before_sha256": expected,
            "after_sha256": sha256_bytes(patched),
            "backup": str(backup),
        }

    cache_src = root / CACHE_PATH
    cache_backup = backup_dir / CACHE_PATH
    cache_backup.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(cache_src, cache_backup)

    runtime_records: dict[str, dict] = {}
    runtime_payloads: dict[str, bytes] = {}
    for target_rel, package_rel in RUNTIME_FILES.items():
        src = package_dir / package_rel
        if not src.is_file():
            raise SystemExit(f"Missing payload: {src}")
        data = src.read_bytes()
        runtime_payloads[target_rel] = data
        runtime_records[target_rel] = {"sha256": sha256_bytes(data), "source": package_rel}

    config_data = render_config(False, "DISARMED", manual_loadout=True)

    # Commit only after every patch and payload has been prepared.
    for rel, patched in prepared.items():
        atomic_write(root / rel, patched)
    for rel, data in runtime_payloads.items():
        atomic_write(root / rel, data)
    atomic_write(root / CONFIG_PATH, config_data)
    cache_src.unlink()

    state = {
        "schema": "smml-gp0-carry-storage-lab-state/1",
        "version": VERSION,
        "installed": True,
        "installed_at_utc": utc_now(),
        "installed_epoch": time.time(),
        "game_root": str(root),
        "files": records,
        "runtime_files": runtime_records,
        "config": {"path": CONFIG_PATH, "sha256": sha256_bytes(config_data), "enabled": False, "run_id": "DISARMED"},
        "cache": {"path": CACHE_PATH, "before_sha256": CACHE_SHA256, "backup": str(cache_backup), "quarantined": []},
        "lab": {"armed": False, "snapshot": None},
    }
    save_state(state_dir, state)
