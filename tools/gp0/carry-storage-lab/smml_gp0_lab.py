def verify_installed_files(state: dict) -> list[str]:
    root = Path(state["game_root"])
    problems = []
    for rel, rec in state.get("files", {}).items():
        p = root / rel
        if not p.is_file() or sha256_file(p) != rec["after_sha256"]:
            problems.append(f"DRIFT {rel}")
    for rel, rec in state.get("runtime_files", {}).items():
        p = root / rel
        if not p.is_file() or sha256_file(p) != rec["sha256"]:
            problems.append(f"DRIFT {rel}")
    cp = root / state["config"]["path"]
    if not cp.is_file() or sha256_file(cp) != state["config"]["sha256"]:
        problems.append(f"DRIFT {state['config']['path']}")
    return problems


def arm(args: argparse.Namespace) -> None:
    require_game_stopped()
    state_dir = args.state_dir.expanduser().resolve()
    state = load_state(state_dir)
    if not state.get("installed"):
        raise SystemExit("Lab hooks are not installed.")
    if state.get("lab", {}).get("armed"):
        raise SystemExit("Lab is already armed.")
    problems = verify_installed_files(state)
    if problems:
        raise SystemExit("Arm refused because installed files drifted:\n" + "\n".join(problems))

    save_root = args.save_root.expanduser().resolve()
    if not save_root.is_dir():
        raise SystemExit(f"Save root is not a directory: {save_root}")

    run_id = datetime.now().strftime("GP0-%Y%m%d-%H%M%S")
    snapshot_parent = state_dir / "snapshots" / run_id
    snapshot_dir = snapshot_parent / "Save"
    manifest = snapshot_tree(save_root, snapshot_dir)
    problems = verify_snapshot(snapshot_dir, manifest)
    if problems:
        raise SystemExit("Snapshot verification failed:\n" + "\n".join(problems[:20]))

    root = Path(state["game_root"])
    config_data = render_config(True, run_id, manual_loadout=not args.no_manual_loadout)
    atomic_write(root / CONFIG_PATH, config_data)
    state["config"] = {"path": CONFIG_PATH, "sha256": sha256_bytes(config_data), "enabled": True, "run_id": run_id}
    state["lab"] = {
        "armed": True,
        "armed_at_utc": utc_now(),
        "armed_epoch": time.time(),
        "run_id": run_id,
        "save_root": str(save_root),
        "snapshot": {
            "dir": str(snapshot_dir),
            "manifest": manifest,
            "restored": False,
        },
    }
    invalidate_current_cache(root, state_dir, state, "arm")
    save_state(state_dir, state)

    print(f"[OK] Lab armed: {run_id}")
    print(f"Recursive Save snapshot: {snapshot_dir}")
    print(f"Snapshot files/dirs: {len(manifest['entries'])}")
    print("Next: launch Scrap Mechanic normally (without -dev) and enter/create the dedicated Survival test world.")


