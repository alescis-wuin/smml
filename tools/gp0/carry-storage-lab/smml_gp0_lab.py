def parse_event_line(line: str) -> dict | None:
    if MARKER not in line:
        return None
    payload = line[line.index(MARKER):].strip()
    parts = payload.split("|")
    result = {"raw": payload}
    if parts:
        result["record"] = parts[0].replace(MARKER, "").strip()
    for part in parts[1:]:
        if "=" in part:
            k, v = part.split("=", 1)
            result[k.strip()] = v.strip()
    return result


def collect_data(state_dir: Path, output: Path) -> dict:
    state = load_state(state_dir)
    root = Path(state["game_root"])
    logs_dir = root / "Logs"
    since = float(state.get("lab", {}).get("armed_epoch") or state.get("installed_epoch", 0))

    candidates = []
    if logs_dir.is_dir():
        for p in sorted(logs_dir.glob("game-*.log")):
            try:
                if p.stat().st_mtime >= since - 60:
                    candidates.append(p)
            except OSError:
                pass

    events = []
    diagnostics = []
    for p in candidates:
        text = p.read_text("utf-8", errors="replace")
        for line_no, line in enumerate(text.splitlines(), 1):
            parsed = parse_event_line(line)
            if parsed:
                parsed["source_log"] = p.name
                parsed["line"] = line_no
                events.append(parsed)
            if any(x in line for x in ("[Lua] ERROR:", "Failed to load file:", "Load failed", "SMMLProbe", MARKER)):
                diagnostics.append({"source_log": p.name, "line": line_no, "text": line})

    storage_rows = [e for e in events if e.get("event") == "storage.case"]
    carry_rows = [e for e in events if e.get("event") in {
        "carry.tryInsert.begin", "carry.raycast", "carry.target", "carry.branch",
        "carry.rpc.client", "carry.rpc.server", "carry.receive.server", "carry.case"
    }]

    event_counts = Counter(e.get("event", "") for e in events)
    carry_success = any(e.get("event") == "carry.case" and e.get("success") == "true" for e in events)
    expected_storage_cases = 16 * 13
    summary = {
        "schema": "smml-gp0-carry-storage-lab-results/1",
        "version": state.get("version"),
        "run_id": state.get("lab", {}).get("run_id"),
        "collected_at_utc": utc_now(),
        "candidate_logs": [p.name for p in candidates],
        "event_count": len(events),
        "event_counts": dict(event_counts),
        "storage_cases_expected": expected_storage_cases,
        "storage_cases_observed": len(storage_rows),
        "storage_matrix_complete": len(storage_rows) == expected_storage_cases,
        "carry_success": carry_success,
        "carry_rpc_server_seen": any(e.get("event") == "carry.rpc.server" and e.get("rpc") == "sv_n_sendItem" for e in events),
        "carry_receive_server_seen": any(e.get("event") == "carry.receive.server" for e in events),
        "lab_complete_seen": any(e.get("event") == "carry.case" and e.get("success") == "true" for e in events),
    }

    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        zf.writestr("summary.json", json.dumps(summary, indent=2, sort_keys=True))
        zf.writestr("state.json", json.dumps(state, indent=2, sort_keys=True))
        zf.writestr("events.json", json.dumps(events, indent=2, sort_keys=True))
        zf.writestr("probe-lines.txt", "\n".join(e["raw"] for e in events) + ("\n" if events else ""))
        zf.writestr("diagnostic-lines.txt", "\n".join(f"{d['source_log']}:{d['line']}: {d['text']}" for d in diagnostics) + ("\n" if diagnostics else ""))

        if events:
            keys = sorted({k for e in events for k in e.keys() if k != "raw"})
            buf = io.StringIO()
            w = csv.DictWriter(buf, fieldnames=keys, extrasaction="ignore")
            w.writeheader()
            for e in events:
                w.writerow({k: e.get(k, "") for k in keys})
            zf.writestr("events.csv", buf.getvalue())

        if storage_rows:
            preferred = [
                "fixtureId", "fixtureTitle", "fixtureUuid", "expectedSlots", "actualSlots",
                "itemId", "itemTitle", "itemUuid", "ready", "canCollect", "beginTransaction",
                "dryRunCollected", "abortIssued", "beforeQuantity", "afterQuantity",
                "unchangedAfterAbort", "revisionBefore", "revisionAfter", "error", "source_log", "line"
            ]
            keys = preferred + sorted({k for r in storage_rows for k in r if k not in set(preferred) | {"raw", "record", "event", "seq", "runtime", "version", "fileLoads", "initCount", "bootstrapCalls", "host"}})
            buf = io.StringIO()
            w = csv.DictWriter(buf, fieldnames=keys, extrasaction="ignore")
            w.writeheader()
            for row in storage_rows:
                w.writerow({k: row.get(k, "") for k in keys})
            zf.writestr("storage-matrix.csv", buf.getvalue())

        if carry_rows:
            keys = sorted({k for r in carry_rows for k in r if k != "raw"})
            buf = io.StringIO()
            w = csv.DictWriter(buf, fieldnames=keys, extrasaction="ignore")
            w.writeheader()
            for row in carry_rows:
                w.writerow({k: row.get(k, "") for k in keys})
            zf.writestr("carry-matrix.csv", buf.getvalue())

        snap = state.get("lab", {}).get("snapshot")
        if snap:
            zf.writestr("snapshot-manifest.json", json.dumps(snap.get("manifest", {}), indent=2, sort_keys=True))

        for p in candidates:
            zf.write(p, f"raw-logs/{p.name}")

    return summary


