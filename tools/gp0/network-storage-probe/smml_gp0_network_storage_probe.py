def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + f".tmp-{os.getpid()}")
    with tmp.open("wb") as f:
        f.write(data)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def default_state_dir() -> Path:
    override = os.environ.get("SMML_GP0_NS_STATE")
    if override:
        return Path(override).expanduser()
    base = os.environ.get("XDG_STATE_HOME")
    if base:
        return Path(base) / "smml" / "gp0-network-storage-probe"
    return Path.home() / ".local" / "state" / "smml" / "gp0-network-storage-probe"


def is_relative_to(child: Path, parent: Path) -> bool:
    try:
        child.relative_to(parent)
        return True
    except ValueError:
        return False


def assert_disjoint(a: Path, b: Path, a_name: str, b_name: str) -> None:
    ar = a.resolve()
    br = b.resolve()
    if ar == br or is_relative_to(ar, br) or is_relative_to(br, ar):
        raise SystemExit(f"Unsafe overlapping roots: {a_name}={ar} {b_name}={br}")


def reject_symlink(path: Path, label: str) -> None:
    if path.is_symlink():
        raise SystemExit(f"Symlink/reparse-style path refused for {label}: {path}")


def game_running() -> list[str]:
    hits: list[str] = []
    proc = Path("/proc")
    if not proc.is_dir():
        return hits
    for child in proc.iterdir():
        if not child.name.isdigit():
            continue
        try:
            cmd = (child / "cmdline").read_bytes().replace(b"\0", b" ").decode("utf-8", "ignore")
            comm = (child / "comm").read_text("utf-8", errors="ignore").strip()
        except OSError:
            continue
        hay = (comm + " " + cmd).lower()
        if "scrapmechanic.exe" in hay or "scrap mechanic/release/scrapmechanic" in hay:
            hits.append(f"pid={child.name} {comm} {cmd[:220]}")
    return hits


def require_game_stopped() -> None:
    hits = game_running()
    if hits:
        raise SystemExit("Scrap Mechanic appears to be running:\n" + "\n".join(hits))


def state_path(state_dir: Path) -> Path:
    return state_dir / "state.json"


def load_state(state_dir: Path) -> dict:
    path = state_path(state_dir)
    if not path.is_file():
        raise SystemExit(f"Probe state not found: {path}")
    state = json.loads(path.read_text("utf-8"))
    if state.get("schema") != "smml-gp0-network-storage-probe-state/1":
        raise SystemExit(f"Unsupported or foreign state schema: {state.get('schema')}")
    return state


def save_state(state_dir: Path, state: dict) -> None:
    state_dir.mkdir(parents=True, exist_ok=True)
    atomic_write(state_path(state_dir), (json.dumps(state, indent=2, sort_keys=True) + "\n").encode("utf-8"))


def lua_bool(value: bool) -> str:
    return "true" if value else "false"


def render_config(enabled: bool, role: str, run_id: str) -> bytes:
    if role not in {"disabled", "host", "client"}:
        raise ValueError(role)
    text = f'''-- Generated by smml_gp0_network_storage_probe.py v{VERSION}.\n__SMML_GP0_NS_CONFIG = {{\n    enabled = {lua_bool(enabled)},\n    role = "{role}",\n    runId = "{run_id}"\n}}\nreturn __SMML_GP0_NS_CONFIG\n'''
    return text.encode("utf-8")


def ensure_prefix() -> str:
    return f'''-- SMML_GP0_NS_BEGIN:bootstrap\nlocal function __smml_gp0_ns_ensureRuntime( source )\n    if type( __SMML_GP0_NS ) ~= "table" or __SMML_GP0_NS.version ~= "{VERSION}" then\n        if type( pcall ) == "function" then\n            local ok, err = pcall( dofile, "$SURVIVAL_DATA/Scripts/SMMLProbeNS/Runtime.lua" )\n            if not ok and type( sm ) == "table" and type( sm.log ) == "table" and type( sm.log.error ) == "function" then\n                sm.log.error( "[SMML-GP0-NS] FALLBACK|event=runtime.load.error|source=" .. tostring( source ) .. "|detail=" .. tostring( err ) )\n            end\n        end\n    end\n    if type( __SMML_GP0_NS ) == "table" and type( __SMML_GP0_NS.bootstrap ) == "function" then\n        __SMML_GP0_NS.bootstrap( source )\n        return true\n    end\n    return false\nend\n__smml_gp0_ns_ensureRuntime( "SurvivalGame.lua.file" )\n-- SMML_GP0_NS_END:bootstrap\n'''


def inject_after_once(text: str, anchor: str, insertion: str, label: str) -> str:
    count = text.count(anchor)
    if count != 1:
        raise RuntimeError(f"{label}: expected one anchor, found {count}: {anchor!r}")
    return text.replace(anchor, anchor + insertion, 1)


