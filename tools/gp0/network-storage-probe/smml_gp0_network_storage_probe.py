def parse_event_line(line: str) -> dict | None:
    if MARKER not in line:
        return None
    payload = line[line.index(MARKER):].strip()
    parts = payload.split("|")
    result = {"raw": payload}
    if parts:
        result["record"] = parts[0].replace(MARKER, "").strip()
    for part in parts[1:]:
        if "=" in part:
            k, v = part.split("=", 1)
            result[k.strip()] = v.strip()
    return result


def bool_event(events: list[dict], event: str, **matches: str) -> bool:
    for e in events:
        if e.get("event") != event:
            continue
        if all(e.get(k) == v for k, v in matches.items()):
            return True
    return False


def summarize_events(events: list[dict], state: dict) -> dict:
    counts = Counter(e.get("event", "") for e in events)
    role = state.get("probe", {}).get("role")
    remote_joins = [e for e in events if e.get("event") == "lifecycle.player.join" and e.get("isHostPlayer") == "false"]
    remote_left = [e for e in events if e.get("event") == "lifecycle.player.left" and e.get("isHostPlayer") == "false"]
    clientdata_set_channels = sorted({e.get("channel") for e in events if e.get("event") == "clientdata.set.ok" and e.get("channel")})
    clientdata_recv_channels = sorted({e.get("channel") for e in events if e.get("event") == "clientdata.receive.client" and e.get("channel")})
    request_replies = {
        rid: any(e.get("event") == "network.reply.client" and e.get("requestId") == rid and e.get("accepted") == "true" for e in events)
        for rid in [f"N-RPC-{i:02d}" for i in range(1, 11)]
    }
    return {
        "schema": "smml-gp0-network-storage-probe-results/1",
        "version": state.get("version"),
        "run_id": state.get("probe", {}).get("run_id"),
        "role": role,
        "collected_at_utc": utc_now(),
        "event_count": len(events),
        "event_counts": dict(counts),
        "server_create_count": counts.get("lifecycle.server.create", 0),
        "client_create_count": counts.get("lifecycle.client.create", 0),
        "remote_join_count": len(remote_joins),
        "remote_left_count": len(remote_left),
        "remote_server_envelope_seen": any(e.get("event") == "network.envelope.server" and e.get("senderIsHost") == "false" for e in events),
        "client_reply_seen": counts.get("network.reply.client", 0) > 0,
        "client_broadcast_seen": counts.get("network.broadcast.client", 0) > 0,
        "clientdata_set_channels": clientdata_set_channels,
        "clientdata_receive_channels": clientdata_recv_channels,
        "clientdata_initial_receive": any(e.get("event") == "clientdata.receive.client" and e.get("reason") == "initial-server-state" for e in events),
        "request_replies_accepted": request_replies,
        "unknown_contract_rejected": bool_event(events, "network.envelope.reject", requestId="N-RPC-06", reason="unknown-contract"),
        "bad_version_rejected": bool_event(events, "network.envelope.reject", requestId="N-RPC-07", reason="unknown-contract"),
        "invalid_payload_rejected": bool_event(events, "network.handler.reject", requestId="N-RPC-08"),
        "handler_throw_seen": bool_event(events, "network.handler.error", requestId="N-RPC-09"),
        "post_throw_success": bool_event(events, "network.handler.ok", requestId="N-RPC-10"),
        "nil_envelope_rejected": bool_event(events, "network.envelope.reject", reason="envelope-not-table"),
        "storage_absent_seen": counts.get("storage.load.absent", 0) > 0,
        "storage_schema1_saved": counts.get("storage.save.schema1", 0) > 0,
        "storage_schema1_loaded": counts.get("storage.load.schema1", 0) > 0,
        "storage_schema2_saved": counts.get("storage.save.schema2", 0) > 0,
        "storage_schema2_loaded": counts.get("storage.load.schema2", 0) > 0,
        "storage_namespace_checks_ok": all(e.get("success") == "true" for e in events if e.get("event") == "storage.namespace.check") and any(e.get("event") == "storage.namespace.check" for e in events),
    }


def collect_data(state_dir: Path, output: Path) -> dict:
    state = load_state(state_dir)
    root = Path(state["game_root"]).resolve()
    logs_dir = root / "Logs"
    since = float(state.get("probe", {}).get("armed_epoch") or state.get("installed_epoch", 0))
    run_id = state.get("probe", {}).get("run_id")

    candidates: list[Path] = []
    if logs_dir.is_dir():
        for p in sorted(logs_dir.glob("game-*.log")):
            try:
                if p.stat().st_mtime >= since - 60:
                    candidates.append(p)
            except OSError:
                pass

    events: list[dict] = []
    diagnostics: list[dict] = []
    for p in candidates:
        text = p.read_text("utf-8", errors="replace")
        for line_no, line in enumerate(text.splitlines(), 1):
            parsed = parse_event_line(line)
            if parsed and (run_id is None or parsed.get("runId") == run_id):
                parsed["source_log"] = p.name
                parsed["line"] = line_no
                events.append(parsed)
            if any(x in line for x in ("[Lua] ERROR:", "Failed to load file:", "Load failed", "SMMLProbeNS", MARKER)):
                diagnostics.append({"source_log": p.name, "line": line_no, "text": line})

    summary = summarize_events(events, state)
    summary["candidate_logs"] = [p.name for p in candidates]

    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        zf.writestr("summary.json", json.dumps(summary, indent=2, sort_keys=True))
        zf.writestr("state.json", json.dumps(state, indent=2, sort_keys=True))
        zf.writestr("events.json", json.dumps(events, indent=2, sort_keys=True))
        zf.writestr("probe-lines.txt", "\n".join(e["raw"] for e in events) + ("\n" if events else ""))
        zf.writestr("diagnostic-lines.txt", "\n".join(f"{d['source_log']}:{d['line']}: {d['text']}" for d in diagnostics) + ("\n" if diagnostics else ""))

        if events:
            keys = sorted({k for e in events for k in e.keys() if k != "raw"})
            buf = io.StringIO()
            w = csv.DictWriter(buf, fieldnames=keys, extrasaction="ignore")
            w.writeheader()
            for e in events:
                w.writerow({k: e.get(k, "") for k in keys})
            zf.writestr("events.csv", buf.getvalue())

        snap = state.get("probe", {}).get("snapshot")
        if snap:
            zf.writestr("snapshot-manifest.json", json.dumps(snap.get("manifest", {}), indent=2, sort_keys=True))

        for p in candidates:
            zf.write(p, f"raw-logs/{p.name}")

    return summary


