def validate_game_root(root: Path) -> None:
    if not root.is_dir() or not (root / "Survival").is_dir() or not (root / "Data").is_dir():
        raise SystemExit(f"Not a Scrap Mechanic root: {root}")
    reject_symlink(root, "game root")
    target = root / TARGET
    reject_symlink(target, TARGET)
    if not target.is_file():
        raise SystemExit(f"Missing target: {target}")
    actual = sha256_file(target)
    if actual != TARGET_SHA256:
        raise SystemExit(
            f"Preflight failed: {TARGET} is not the clean 1.0.6.889 baseline.\n"
            f"  expected {TARGET_SHA256}\n  actual   {actual}\n"
            "Restore/uninstall any previous probe before installing this one."
        )
    for rel in list(RUNTIME_FILES) + [CONFIG_PATH]:
        if (root / rel).exists():
            raise SystemExit(f"Preflight failed: owned probe path already exists: {rel}")


def invalidate_cache(root: Path, state_dir: Path, state: dict, reason: str) -> None:
    cache = root / CACHE_PATH
    if cache.exists():
        reject_symlink(cache, CACHE_PATH)
        quarantine = state_dir / "quarantine" / f"core_data.cbo.{reason}-{datetime.now().strftime('%Y%m%d-%H%M%S-%f')}"
        quarantine.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(cache), str(quarantine))
        state.setdefault("cache", {}).setdefault("quarantined", []).append(str(quarantine))


def install(args: argparse.Namespace) -> None:
    require_game_stopped()
    root = args.game_root.expanduser().resolve()
    state_dir = args.state_dir.expanduser().resolve()
    assert_disjoint(root, state_dir, "game_root", "state_dir")
    validate_game_root(root)
    if state_path(state_dir).exists():
        old = json.loads(state_path(state_dir).read_text("utf-8"))
        if old.get("installed"):
            raise SystemExit(f"Probe already installed according to {state_path(state_dir)}")

    package_dir = Path(__file__).resolve().parent
    backup_dir = state_dir / "backups"
    backup_dir.mkdir(parents=True, exist_ok=True)

    original = (root / TARGET).read_bytes()
    patched = apply_patch(original)
    target_backup = backup_dir / TARGET
    target_backup.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(root / TARGET, target_backup)

    runtime_records: dict[str, dict] = {}
    runtime_payloads: dict[str, bytes] = {}
    for target_rel, package_rel in RUNTIME_FILES.items():
        src = package_dir / package_rel
        if not src.is_file():
            raise SystemExit(f"Missing payload: {src}")
        data = src.read_bytes()
        runtime_payloads[target_rel] = data
        runtime_records[target_rel] = {"sha256": sha256_bytes(data), "source": package_rel}

    config_data = render_config(False, "disabled", "DISARMED")

    cache = root / CACHE_PATH
    cache_record = {"path": CACHE_PATH, "existed": cache.is_file(), "quarantined": []}
    if cache.is_file():
        reject_symlink(cache, CACHE_PATH)
        cache_backup = backup_dir / CACHE_PATH
        cache_backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(cache, cache_backup)
        cache_record.update({"before_sha256": sha256_file(cache), "backup": str(cache_backup)})

    state = {
        "schema": "smml-gp0-network-storage-probe-state/1",
        "version": VERSION,
        "installed": False,
        "phase": "prepared",
        "prepared_at_utc": utc_now(),
        "game_root": str(root),
        "files": {
            TARGET: {
                "before_sha256": TARGET_SHA256,
                "after_sha256": sha256_bytes(patched),
                "backup": str(target_backup),
            }
        },
        "runtime_files": runtime_records,
        "config": {
            "path": CONFIG_PATH,
            "sha256": sha256_bytes(config_data),
            "enabled": False,
            "role": "disabled",
            "run_id": "DISARMED",
        },
        "cache": cache_record,
        "probe": {"armed": False, "role": None, "run_id": None, "snapshot": None},
    }
    save_state(state_dir, state)

    atomic_write(root / TARGET, patched)
    for rel, data in runtime_payloads.items():
        atomic_write(root / rel, data)
    atomic_write(root / CONFIG_PATH, config_data)
    invalidate_cache(root, state_dir, state, "install")

    state["installed"] = True
    state["phase"] = "installed"
    state["installed_at_utc"] = utc_now()
    state["installed_epoch"] = time.time()
    save_state(state_dir, state)

    print("[OK] SMML GP0.5 Network/Storage probe installed (passive/disarmed)")
    print(f"Game:  {root}")
    print(f"State: {state_dir}")
    print(f"Patched: {TARGET}")
    print(f"Targeted cache invalidated: {CACHE_PATH}")


def verify_installed_files(state: dict) -> list[str]:
    root = Path(state["game_root"]).resolve()
    problems: list[str] = []
    for rel, rec in state.get("files", {}).items():
        p = root / rel
        if not p.is_file() or sha256_file(p) != rec.get("after_sha256"):
            problems.append(f"DRIFT {rel}")
    for rel, rec in state.get("runtime_files", {}).items():
        p = root / rel
        if not p.is_file() or sha256_file(p) != rec.get("sha256"):
            problems.append(f"DRIFT {rel}")
    cfg = root / state["config"]["path"]
    if not cfg.is_file() or sha256_file(cfg) != state["config"].get("sha256"):
        problems.append(f"DRIFT {state['config']['path']}")
    return problems


def snapshot_tree(source: Path, destination: Path) -> dict:
    if destination.exists():
        raise SystemExit(f"Snapshot destination already exists: {destination}")
    reject_symlink(source, "save root")
    for p in source.rglob("*"):
        if p.is_symlink():
            raise SystemExit(f"Save snapshot refused because a symlink exists: {p}")

    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(source, destination, symlinks=False)
    entries = []
    for p in sorted(destination.rglob("*")):
        rel = p.relative_to(destination).as_posix()
        if p.is_file():
            entries.append({"path": rel, "kind": "file", "size": p.stat().st_size, "sha256": sha256_file(p)})
        elif p.is_dir():
            entries.append({"path": rel, "kind": "dir"})
    manifest = {
        "schema": "smml-gp0-save-snapshot/1",
        "created_at_utc": utc_now(),
        "source": str(source),
        "entries": entries,
    }
    manifest_bytes = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    atomic_write(destination.parent / "snapshot-manifest.json", manifest_bytes)
    manifest["manifest_sha256"] = sha256_bytes(manifest_bytes)
    return manifest


def verify_snapshot(snapshot_dir: Path, manifest: dict) -> list[str]:
    problems: list[str] = []
    for entry in manifest.get("entries", []):
        p = snapshot_dir / entry["path"]
        if entry["kind"] == "file":
            if not p.is_file() or p.stat().st_size != entry["size"] or sha256_file(p) != entry["sha256"]:
                problems.append(f"DRIFT {entry['path']}")
        elif entry["kind"] == "dir" and not p.is_dir():
            problems.append(f"MISSING DIR {entry['path']}")
    return problems


def arm_common(state_dir: Path, state: dict, role: str, run_id: str) -> None:
    root = Path(state["game_root"]).resolve()
    problems = verify_installed_files(state)
    if problems:
        raise SystemExit("Arm refused because installed files drifted:\n" + "\n".join(problems))
    config_data = render_config(True, role, run_id)
    atomic_write(root / CONFIG_PATH, config_data)
    state["config"] = {
        "path": CONFIG_PATH,
        "sha256": sha256_bytes(config_data),
        "enabled": True,
        "role": role,
        "run_id": run_id,
    }
    state["probe"]["armed"] = True
    state["probe"]["role"] = role
    state["probe"]["run_id"] = run_id
    state["probe"]["armed_at_utc"] = utc_now()
    state["probe"]["armed_epoch"] = time.time()
    invalidate_cache(root, state_dir, state, f"arm-{role}")


def arm_host(args: argparse.Namespace) -> None:
    require_game_stopped()
    state_dir = args.state_dir.expanduser().resolve()
    state = load_state(state_dir)
    if not state.get("installed"):
        raise SystemExit("Probe is not installed.")
    if state.get("probe", {}).get("armed"):
        raise SystemExit("Probe is already armed.")

    root = Path(state["game_root"]).resolve()
    save_root = args.save_root.expanduser().resolve()
    if not save_root.is_dir():
        raise SystemExit(f"Save root is not a directory: {save_root}")
    assert_disjoint(root, state_dir, "game_root", "state_dir")
    assert_disjoint(save_root, state_dir, "save_root", "state_dir")
    assert_disjoint(root, save_root, "game_root", "save_root")

    run_id = args.run_id or datetime.now().strftime("GP05-%Y%m%d-%H%M%S")
    snapshot_parent = state_dir / "snapshots" / run_id
    snapshot_dir = snapshot_parent / "Save"
    manifest = snapshot_tree(save_root, snapshot_dir)
    problems = verify_snapshot(snapshot_dir, manifest)
    if problems:
        raise SystemExit("Snapshot verification failed:\n" + "\n".join(problems[:20]))

    arm_common(state_dir, state, "host", run_id)
    state["probe"]["save_root"] = str(save_root)
    state["probe"]["snapshot"] = {"dir": str(snapshot_dir), "manifest": manifest, "restored": False}
    save_state(state_dir, state)

