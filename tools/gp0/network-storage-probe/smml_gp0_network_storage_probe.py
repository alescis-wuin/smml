def restore_save_internal(state_dir: Path, state: dict) -> None:
    probe_state = state.get("probe", {})
    if probe_state.get("role") != "host":
        raise SystemExit("This state is not the host role; no Save snapshot is expected.")
    snap = probe_state.get("snapshot")
    if not snap:
        raise SystemExit("No Save snapshot is recorded in host state.")
    if snap.get("restored"):
        return

    snapshot_dir = Path(snap["dir"]).resolve()
    manifest = snap["manifest"]
    problems = verify_snapshot(snapshot_dir, manifest)
    if problems:
        raise SystemExit("Snapshot integrity failure:\n" + "\n".join(problems[:20]))

    save_root = Path(probe_state["save_root"]).resolve()
    assert_disjoint(save_root, state_dir, "save_root", "state_dir")
    quarantine = state_dir / "quarantine" / f"Save.post-probe-{datetime.now().strftime('%Y%m%d-%H%M%S')}"
    quarantine.parent.mkdir(parents=True, exist_ok=True)
    if save_root.exists():
        shutil.move(str(save_root), str(quarantine))
    shutil.copytree(snapshot_dir, save_root, symlinks=False)

    restore_problems = verify_snapshot(save_root, manifest)
    if restore_problems:
        raise SystemExit("Restored Save verification failed:\n" + "\n".join(restore_problems[:20]))

    snap["restored"] = True
    snap["restored_at_utc"] = utc_now()
    snap["post_probe_quarantine"] = str(quarantine)
    disable_config(state_dir, state, "restore-save")


